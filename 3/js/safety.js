// 위기 표현 판정(docs/safety-review.md 2절 그대로). 판정은 기기 안 메모리에서만 한다.
// 결과·맞은 말·메모를 저장·전송·console 출력하지 않는다.
const norm = (s) => s.normalize('NFC').replace(/[\s.,!?~…·'"`^;:()\-ㅠㅜㅡ]/g, '');
const STRIP = [ // 1단계: 과장·다른 뜻 구간을 먼저 지운다
  /(쪽팔|창피|부끄|민망)[가-힣]{0,4}죽고[싶십]/g, /죽고[싶십](지|진|지는)않/g, /자살(골|예방)/g, /유서깊/g,
];
const HIT = [ // 2단계: 하나라도 맞으면 안내 후보
  /죽고[싶십]/, /죽어버리고[싶십]/, /뒤지고[싶십]/, /죽는게(나을|낫)/,
  /살기[싫실]/, /살고[싶십](지|진|지는)않/, /그만살고[싶십]/, /살아서뭐(해|하)/, /살아(갈|야할)이유가?없/, /사는게의미가?없/,
  /(사라|없어)(지고|져버리고)[싶십]/, /내가(사라|없어)지면/, /(나|내가)없는게(나|낫)/, /내가없어야/,
  /태어나지(말았|않았으면)/, /안태어났으면/, /영원히잠들/, /(깨어나|눈뜨)지않았으면/,
  /목숨을?끊/, /자살/, /자해/, /극단적인?선택/, /유서/,
];
export function needsHelp(memo) {
  if (!memo) return false;
  let t = norm(String(memo));
  for (const r of STRIP) t = t.replace(r, '');
  return HIT.some((r) => r.test(t));
}
