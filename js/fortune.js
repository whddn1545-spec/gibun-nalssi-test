/**
 * 오늘의 운세. key: 오늘 날짜, seed: 사람마다 정해 둔 수,
 * ctx: { birthday('M-D'), count(기록한 날 수), hard(요즘 힘든 날 수), special }
 */
export function fortune(key, seed, { birthday = '', count = 0, hard = 0, special = null } = {}) {
  const day = dayPillar(key);
  const sign = signOf(birthday);
  const me = sign || `p${seed}`;           // 같은 별자리·같은 날이면 분야별 흐름이 같다
  const base = `${me}|${key}`;
  const mine = `${seed}|${key}`;            // 행운 항목은 사람마다
  const fields = FIELDS.map((f) => {
    let lv = 1 + (hash(`${base}|${f.id}`) % 3);
    if (hard >= 3 && lv < 2) lv = 2;        // 요즘 힘든 사람에겐 낮은 날을 덜 보여 준다
    if (special === 'birthday') lv = 3;
    const text = `${pick(LEAD[f.id][lv], `${base}|${f.id}|l`)} ${pick(TIP[f.id], `${mine}|${f.id}|t`)}`;
    return { id: f.id, name: f.name, lv, word: STAR_WORD[lv], text };
  });
  const all = fields[0];
  const word = special === 'birthday' ? '생일 축하해요! 오늘은 모든 구름이 축하하러 오는 날이에요'
    : hard >= 3 ? pick(WORD_GENTLE, `${mine}|w`) : pick(WORD[all.lv], `${mine}|w`);
  const open = ITEMS.filter((it) => count >= it.need);
  const item = open.length ? pick(open, `${mine}|item`) : ITEMS[0];
  return {
    day, sign,
    sky: `${day.name} · ${EL_LINE[day.el]}`,
    word,
    fields,
    color: pick(COLORS, `${mine}|color`),
    thing: pick(THINGS, `${mine}|thing`),
    initial: pick(INITIALS, `${mine}|ini`),
    initialHint: pick(INITIAL_HINT, `${mine}|inih`),
    number: 1 + (hash(`${mine}|num`) % 45),
    dir: pick(DIRS, `${mine}|dir`),
    time: hourText(pick(HOURS, `${mine}|time`)),
    item,
    itemOpen: count >= item.need,
  };
}
