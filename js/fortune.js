/** 'M-D' → 별자리 이름 (없으면 null) */
export function signOf(birthday) {
  const mm = /^(\d{1,2})-(\d{1,2})$/.exec(birthday || '');
  if (!mm) return null;
  const v = Number(mm[1]) * 100 + Number(mm[2]);
  let name = SIGNS[0][0];
  for (const [n, m, d] of SIGNS.slice(1)) if (v >= m * 100 + d) name = n;
  if (v >= 1222) name = SIGNS[0][0];
  return name;
}

