/** 날짜(YYYY-MM-DD)의 일진: 2000-01-01이 무오일(54번째)인 것을 기준으로 센다 */
export function dayPillar(key) {
  const [y, m, d] = key.split('-').map(Number);
  const days = Math.round((Date.UTC(y, m - 1, d) - Date.UTC(2000, 0, 1)) / 86400000);
  const i = (((54 + days) % 60) + 60) % 60;
  // 화면에는 '붉은 원숭이의 날'처럼 띠 이름으로 보여 준다(일진 이름 중 욕처럼 읽히는 것이 있어서)
  return { i, code: `${STEMS[i % 10]}${BRANCHES[i % 12]}`, name: `${STEM_COLOR[i % 10]} ${ANIMALS[i % 12]}의 날`, animal: ANIMALS[i % 12], el: STEM_EL[i % 10] };
}
